//! Generate language bindings from the Harbor owner schema; `--check` never writes.
use serde_json::Value;
use sha2::{Digest, Sha256};
use std::{env, error::Error, fmt::Write as _, fs, path::Path};

fn snake(name: &str) -> String {
    let mut result = String::new();
    for letter in name.chars() {
        if letter.is_ascii_uppercase() {
            result.push('_');
            result.push(letter.to_ascii_lowercase());
        } else {
            result.push(letter);
        }
    }
    result
}

fn pascal(name: &str) -> String {
    name.split('-')
        .map(|word| {
            let mut chars = word.chars();
            chars.next().unwrap().to_ascii_uppercase().to_string() + chars.as_str()
        })
        .collect()
}

fn rust_type(definition: &Value) -> String {
    if let Some(name) = definition.as_str() {
        return name.to_owned();
    }
    if definition.get("const").is_some() {
        return "u32".into();
    }
    if let Some(items) = definition.get("items") {
        return format!("Vec<{}>", rust_type(items));
    }
    panic!("unsupported schema definition");
}

fn ts_type(definition: &Value) -> String {
    if let Some(name) = definition.as_str() {
        return if name == "bool" { "boolean" } else { name }.into();
    }
    if definition["type"] == "string" {
        return "string".into();
    }
    if let Some(value) = definition.get("const") {
        return value.to_string();
    }
    if let Some(items) = definition.get("items") {
        return format!("{}[]", ts_type(items));
    }
    if let Some(choices) = definition["enum"].as_array() {
        return choices
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    if let Some(fields) = definition["fields"].as_object() {
        return format!(
            "{{ {} }}",
            fields
                .iter()
                .map(|(key, value)| format!("{key}: {}", ts_type(value)))
                .collect::<Vec<_>>()
                .join("; ")
        );
    }
    if let Some(variants) = definition["variants"].as_object() {
        let tag = definition["tag"].as_str().unwrap();
        return variants
            .iter()
            .map(|(key, value)| format!("({{ {tag}: {key:?} }} & {})", ts_type(value)))
            .collect::<Vec<_>>()
            .join(" | ");
    }
    panic!("unsupported schema definition");
}

fn generate(root: &Path, check: bool, command: bool) -> Result<(), Box<dyn Error>> {
    let bytes = fs::read(root.join(if command {
        "protocol/commands.json"
    } else {
        "protocol/execution.json"
    }))?;
    let mut schema: Value = serde_json::from_slice(&bytes)?;
    let digest = format!("{:x}", Sha256::digest(&bytes));
    let header = "// Generated by harbor-llm-codegen. Do not edit.\n";
    let mut rust = format!(
        "{header}use serde::{{Deserialize, Serialize}};\n\n/// SHA-256 of the exact owner schema bytes.\npub const SCHEMA_DIGEST: &str = {digest:?};\n\n"
    );
    let mut types = header.to_owned();
    if command {
        let original = fs::read(root.join("protocol/execution.json"))?;
        if schema["executionSchemaDigest"] != format!("{:x}", Sha256::digest(&original)) {
            return Err("command schema dependency drift".into());
        }
        let policy: Value =
            serde_json::from_slice(&fs::read(root.join("protocol/transport.json"))?)?;
        let observation: Value = serde_json::from_slice(&original)?;
        if schema["maxFrameBytes"] != observation["maxFrameBytes"]
            || schema["maxInputBytes"] != policy["maxInputBytes"]
            || schema["maxOutputBytes"] != policy["maxOutputBytes"]
            || schema["definitions"]["ChunkData"]["maxBytes"].as_u64()
                != schema["maxChunkBytes"].as_u64().map(|bytes| bytes * 2)
        {
            return Err("command transport ceiling drift".into());
        }
        let imports = schema["imports"]
            .as_array()
            .unwrap()
            .iter()
            .map(|value| value.as_str().unwrap())
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(rust, "use super::{{{imports}}};\n")?;
        writeln!(types, "import type {{ {imports} }} from \"./types.js\";\n")?;
    }
    for (name, definition) in schema["definitions"].as_object().unwrap() {
        writeln!(types, "export type {name} = {};\n", ts_type(definition))?;
        writeln!(
            rust,
            "/// Structural wire representation of `{name}`; decoding validates constraints."
        )?;
        if definition["type"] == "string" {
            writeln!(rust, "pub type {name} = String;\n")?;
            continue;
        }
        writeln!(
            rust,
            "#[derive(Clone, Debug, Eq, PartialEq, Deserialize, Serialize)]"
        )?;
        if let Some(choices) = definition["enum"].as_array() {
            writeln!(rust, "pub enum {name} {{")?;
            for choice in choices {
                let value = choice.as_str().unwrap();
                writeln!(
                    rust,
                    "    /// `{value}`.\n    #[serde(rename = {value:?})]\n    {},",
                    pascal(value)
                )?;
            }
        } else if let Some(fields) = definition["fields"].as_object() {
            writeln!(
                rust,
                "#[serde(rename_all = \"camelCase\", deny_unknown_fields)]\npub struct {name} {{"
            )?;
            for (field, definition) in fields {
                writeln!(
                    rust,
                    "    /// Wire field `{field}`.\n    pub {}: {},",
                    snake(field),
                    rust_type(definition)
                )?;
            }
        } else if let Some(variants) = definition["variants"].as_object() {
            writeln!(
                rust,
                "#[serde(tag = {:?})]\npub enum {name} {{",
                definition["tag"].as_str().unwrap()
            )?;
            for (variant, definition) in variants {
                writeln!(
                    rust,
                    "    /// `{variant}`.\n    #[serde(rename = {variant:?})]\n    {}({}),",
                    pascal(variant),
                    rust_type(definition)
                )?;
            }
        } else {
            return Err("unsupported schema definition".into());
        }
        writeln!(rust, "}}\n")?;
    }
    if command {
        let original: Value =
            serde_json::from_slice(&fs::read(root.join("protocol/execution.json"))?)?;
        let mut definitions = original["definitions"].as_object().unwrap().clone();
        definitions.extend(schema["definitions"].as_object().unwrap().clone());
        schema["definitions"] = Value::Object(definitions);
    }
    let metadata = format!(
        "{header}export const schemaDigest = {digest:?};\nfunction deepFreeze(value) {{\n  if (typeof value === \"object\" && value !== null) {{\n    for (const child of Object.values(value)) deepFreeze(child);\n    Object.freeze(value);\n  }}\n  return value;\n}}\nexport const schema = deepFreeze({schema});\n"
    );
    let rust = rust.trim_end().to_owned() + "\n";
    let types = types.trim_end().to_owned() + "\n";
    let files = if command {
        [
            ("rust/command_types.rs", rust),
            ("src/execution/command-types.d.ts", types),
            ("src/execution/command-schema.mjs", metadata),
        ]
    } else {
        [
            ("rust/types.rs", rust),
            ("src/execution/types.d.ts", types),
            ("src/execution/schema.mjs", metadata),
        ]
    };
    for (relative, content) in files {
        let path = root.join(relative);
        if check {
            if fs::read(&path)? != content.as_bytes() {
                return Err(format!("generated binding drift: {relative}").into());
            }
        } else {
            fs::create_dir_all(path.parent().unwrap())?;
            fs::write(path, content)?;
        }
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<_> = env::args().skip(1).collect();
    let (check, root) = match args.as_slice() {
        [root] => (false, root),
        [flag, root] if flag == "--check" => (true, root),
        _ => return Err("usage: harbor-llm-codegen [--check] OWNER_ROOT".into()),
    };
    generate(Path::new(root), check, false)?;
    generate(Path::new(root), check, true)
}
